# 1. Defect on the first round to avoid the initial sucker payoff and test the
# opponent's response. 2. Defect on rounds 999 and 1000 to exploit the finite
# game horizon. 3. If the opponent defected in both of the previous two rounds,
# defect to retaliate against sustained aggression. 4. If the current round is a
# multiple of 10 and the opponent has cooperated in every round since your last
# defection, defect to exploit unconditional cooperators. 5. Otherwise,
# cooperate.

class Neutral_4(LLM_Strategy):
  n = 4
  attitude = Attitude.NEUTRAL
  game = 'classic'
  rounds = 1000
  noise = 0

  @auto_update_score
  def strategy(self, opponent: axl.player.Player) -> axl.Action:
      current_round = len(self.history) + 1
  
      # 1. Defect on the first round.
      if current_round == 1:
          return axl.Action.D
  
      # 2. Defect on rounds 999 and 1000.
      if current_round == 999 or current_round == 1000:
          return axl.Action.D
  
      # 3. Retaliation: opponent defected in both of the previous two rounds.
      if len(opponent.history) >= 2 and opponent.history[-1] == axl.Action.D and opponent.history[-2] == axl.Action.D:
          return axl.Action.D
  
      # 4. Exploit if round is multiple of 10 and opponent always cooperated since our last defection.
      if current_round % 10 == 0:
          # Find the most recent round where we defected.
          last_defection_round = None
          for i in range(len(self.history) - 1, -1, -1):
              if self.history[i] == axl.Action.D:
                  last_defection_round = i + 1  # convert to 1-indexed round number
                  break
  
          if last_defection_round is not None:
              # rounds after our last defection are opponent.history[last_defection_round:]
              if len(opponent.history) > last_defection_round:
                  if all(move == axl.Action.C for move in opponent.history[last_defection_round:]):
                      return axl.Action.D
              else:
                  # No rounds since last defection: condition holds vacuously.
                  return axl.Action.D
          else:
              # We never defected (should not happen, but handle gracefully).
              if all(move == axl.Action.C for move in opponent.history):
                  return axl.Action.D
  
      # 5. Otherwise cooperate.
      return axl.Action.C






