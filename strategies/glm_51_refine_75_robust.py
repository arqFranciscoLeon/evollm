# 1. If it is the first round, cooperate. 2. If it is the second round, defect
# to test the opponent. 3. If it is the third round, cooperate to observe the
# opponent's reaction to your defection. 4. If the opponent defected in the
# second round, defect for the remainder of the game to protect yourself from a
# hostile opponent. 5. If the opponent cooperated in the second round but
# defected in the third round, cooperate for the remainder of the game to secure
# mutual cooperation with a retaliating opponent. 6. If the opponent cooperated
# in both the second and third rounds, defect for the remainder of the game to
# continuously exploit an unconditionally cooperative opponent.

class Aggressive_1(LLM_Strategy):
  n = 1
  attitude = Attitude.AGGRESSIVE
  game = 'classic'
  rounds = 1000
  noise = 0

  @auto_update_score
  def strategy(self, opponent: axl.player.Player) -> axl.Action:
      if self.first_round():
          return axl.Action.C
  
      round_number = len(self.history) + 1
  
      if round_number == 2:
          return axl.Action.D
  
      if round_number == 3:
          return axl.Action.C
  
      if len(opponent.history) >= 2:
          opp_second = opponent.history[1]
          if opp_second == axl.Action.D:
              return axl.Action.D
  
      if len(opponent.history) >= 3:
          opp_second = opponent.history[1]
          opp_third = opponent.history[2]
          if opp_second == axl.Action.C and opp_third == axl.Action.D:
              return axl.Action.C
          if opp_second == axl.Action.C and opp_third == axl.Action.C:
              return axl.Action.D
  
      return axl.Action.C






# 1. In the first round, play Cooperate. 2. If it is round 1000, play Defect. 3.
# If both you and the opponent played Defect in the previous round, play
# Cooperate. 4. If the opponent played Defect in the previous round and you
# played Cooperate, play Defect. 5. If the opponent played Cooperate in the
# previous round, play Cooperate.

class Cooperative_1(LLM_Strategy):
  n = 1
  attitude = Attitude.COOPERATIVE
  game = 'classic'
  rounds = 1000
  noise = 0

  @auto_update_score
  def strategy(self, opponent: axl.player.Player) -> axl.Action:
      if len(self.history) == 999:
          return axl.Action.D
      if len(self.history) == 0:
          return axl.Action.C
      my_prev = self.history[-1]
      opp_prev = opponent.history[-1]
      if opp_prev == axl.Action.C:
          return axl.Action.C
      else:
          if my_prev == axl.Action.D:
              return axl.Action.C
          else:
              return axl.Action.D






# 1. If the current round is 996 or later, defect. 2. If the opponent has
# cooperated for the last 10 consecutive rounds and has never defected in the
# game, defect. 3. If the opponent's last four moves alternated strictly between
# defect and cooperate in any order, defect. 4. If both you and the opponent
# defected in the previous round, cooperate. 5. If the opponent defected in the
# previous round, defect. 6. Cooperate.

class Neutral_1(LLM_Strategy):
  n = 1
  attitude = Attitude.NEUTRAL
  game = 'classic'
  rounds = 1000
  noise = 0

  @auto_update_score
  def strategy(self, opponent: axl.player.Player) -> axl.Action:
      if len(self.history) >= 996:
          return axl.Action.D
  
      if opponent.history.defections == 0 and len(opponent.history) >= 10 and opponent.history[-10:] == [axl.Action.C] * 10:
          return axl.Action.D
  
      if len(opponent.history) >= 4:
          last_four = opponent.history[-4:]
          if all(last_four[i] != last_four[i + 1] for i in range(3)) and set(last_four) == {axl.Action.C, axl.Action.D}:
              return axl.Action.D
  
      if len(self.history) > 0 and self.history[-1] == axl.Action.D and opponent.history[-1] == axl.Action.D:
          return axl.Action.C
  
      if len(opponent.history) > 0 and opponent.history[-1] == axl.Action.D:
          return axl.Action.D
  
      return axl.Action.C






