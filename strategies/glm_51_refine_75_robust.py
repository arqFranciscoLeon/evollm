class Aggressive_3(LLM_Strategy):
  n = 3
  attitude = Attitude.AGGRESSIVE
  game = 'classic'
  rounds = 1000
  noise = 0

  @auto_update_score
  def strategy(self, opponent: axl.player.Player) -> axl.Action:
      if self.first_round():
          self._mode = "cooperate"
          self._switch_round = None
          self._last_opponent_defections = 0
          return axl.Action.C
  
      round_num = len(self.history) + 1
      opp_defections = opponent.history.defections
      my_defections = self.history.defections
  
      # Detect sustained defection and switch to retaliation.
      if self._mode == "cooperate":
          if opp_defections >= 3 and round_num >= 10:
              self._mode = "retaliate"
              self._switch_round = round_num
          elif len(opponent.history) >= 5 and opponent.history[-5:].count(axl.Action.D) >= 4:
              self._mode = "retaliate"
              self._switch_round = round_num
  
      # In retaliation mode, defect for a while, but occasionally forgive.
      if self._mode == "retaliate":
          if self._switch_round is not None and round_num - self._switch_round >= 8:
              # Give cooperation a chance if opponent has recently softened.
              if len(opponent.history) >= 3 and opponent.history[-3:].count(axl.Action.C) >= 2:
                  self._mode = "cooperate"
                  return axl.Action.C
          if len(opponent.history) >= 2 and opponent.history[-2:] == [axl.Action.C, axl.Action.C]:
              return axl.Action.C
          return axl.Action.D
  
      # Default behavior: mostly cooperate, but punish immediate exploitation.
      if opponent.history[-1] == axl.Action.D and len(opponent.history) >= 2 and opponent.history[-2] == axl.Action.C:
          return axl.Action.D
  
      # If we are behind by a lot late in the game, become more aggressive.
      if round_num > 900 and self.score + 20 < opponent.score:
          return axl.Action.D
  
      # Small endgame adjustment: if opponent has been mostly cooperative, stay cooperative.
      if len(opponent.history) >= 10 and opponent.history[-10:].count(axl.Action.D) <= 2:
          return axl.Action.C
  
      return axl.Action.C






